const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { stripTypeScriptTypes } = require('node:module');
const storage = new Map();
const localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v), removeItem: k => storage.delete(k) };
const source = stripTypeScriptTypes(fs.readFileSync('src/office/prompt-draft.ts', 'utf8')).replace(/export function (\w+)/g, 'exports.$1 = function $1');
const boot = () => { const exports = {}; vm.runInNewContext(source, { exports, localStorage }); return exports; };
let drafts = boot();
const prompt = 'Keep every word\n\nincluding umlauts: Fragebogen, prüfen';
assert.equal(drafts.writePromptDraft('chat:one', prompt), true);
drafts.writePromptDraft('hire:project', 'Another job');
drafts = boot();
assert.equal(drafts.readPromptDraft('chat:one'), prompt);
assert.equal(drafts.readPromptDraft('chat:two'), '');
assert.equal(drafts.readPromptDraft('hire:project'), 'Another job');
drafts.writePromptDraft('chat:one', '');
assert.equal(boot().readPromptDraft('chat:one'), '');
localStorage.setItem = () => { throw new Error('disk full'); };
assert.equal(drafts.writePromptDraft('hire:project', 'replacement'), false);
assert.equal(boot().readPromptDraft('hire:project'), 'Another job');
console.log('Prompt drafts: restart recovery, separate threads/projects, successful-send clearing and storage failure passed.');
