import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const source = await readFile(new URL('../src/office/thread-state.ts', import.meta.url), 'utf8');
const code = (await transformWithOxc(source, 'thread-state.ts')).code.replace(/^export /gm, '').replace(/export\s*\{[^}]*\};?/g, '');
const state = new Function(`${code};return threadState`)();
const base = { id:'thread',runStatus:null,updatedAt:'2026-11-09T12:00:00Z' };
const check = (patch, tone, label, review = null) => { const s=state({...base,...patch},review); assert.equal(s.tone,tone);assert.equal(s.label,label); };
check({}, '', '');
check({runStatus:'running',lastStatus:'failed'}, 'work', 'Working');
check({runStatus:'queued',lastStatus:'failed'}, 'queued', 'Queued');
check({runStatus:'failed',lastStatus:'completed'}, 'fail', 'Failed');
check({runStatus:'running',question:'Approve?'}, 'ask', 'Needs input');
check({settled:true,runStatus:'running',question:'Old?'}, '', 'Collected');
check({job:{state:'running',name:'Build'}}, 'work', 'In background');
check({job:{state:'failed',name:'Build'}}, 'fail', 'Job failed');
check({runStatus:'completed'}, 'review', 'Needs your review', 'Needs your review');
check({unseen:true,lastStatus:'completed'}, 'done', 'Done');
check({unseen:false,lastStatus:'completed'}, 'done', 'Done');
check({runStatus:'completed',lastStatus:'failed',unseen:false}, 'done', 'Done');
check({runStatus:'error',lastStatus:'completed'}, 'fail', 'Failed');
for(const runStatus of ['interrupted','cancelled','canceled']) check({runStatus,lastStatus:'failed'}, '', 'Stopped');
assert.equal(state({...base,question:'Approve?'},null,true).label,'With the Orchestrator');
console.log('Thread state precedence passed: live work, queued, input, background jobs, failures, stopped, review, unread completion and collected.');
