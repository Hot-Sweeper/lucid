import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const read = (file) => readFile(new URL(`../src/${file}`, import.meta.url), 'utf8');
// The vocabulary itself comes from src/ui/status.ts; only its STATUS table is needed here.
const vocabulary = (await read('ui/status.ts')).match(/export const STATUS[\s\S]*?\n\};/)[0];
const source = vocabulary + '\n' + (await read('office/thread-state.ts')).replace(/^import .*$/gm, '');
const code = (await transformWithOxc(source, 'thread-state.ts')).code.replace(/^export /gm, '').replace(/export\s*\{[^}]*\};?/g, '');
const state = new Function(`${code};return threadState`)();
const base = { id:'thread',runStatus:null,updatedAt:'2026-11-09T12:00:00Z' };
const check = (patch, tone, label, review = null, detail) => { const s=state({...base,...patch},review); assert.equal(s.tone,tone);assert.equal(s.label,label); if (detail !== undefined) assert.equal(s.detail,detail); return s; };
check({}, '', '');
assert.equal(check({runStatus:'running',lastStatus:'failed'}, 'working', 'Working').run, true);
assert.equal(check({runStatus:'queued',lastStatus:'failed'}, 'working', 'Working', null, 'Queued').run, true);
check({runStatus:'failed',lastStatus:'completed'}, 'needs', 'Needs you', null, 'Run failed');
check({runStatus:'running',question:'Approve?'}, 'needs', 'Needs you', null, 'Asked a question');
check({settled:true,runStatus:'running',question:'Old?'}, 'settled', 'Settled');
assert.notEqual(check({job:{state:'running',name:'Build'}}, 'working', 'Working').run, true);
check({job:{state:'failed',name:'Build'}}, 'needs', 'Needs you', null, 'Job failed: Build');
check({runStatus:'completed'}, 'needs', 'Needs you', 'Needs your review', 'Needs your review');
check({runStatus:'completed'}, 'done', 'Done', 'Ready to collect');
check({runStatus:'completed'}, 'working', 'Working', 'Orchestrator reviewing');
check({unseen:true,lastStatus:'completed'}, 'done', 'Done');
check({unseen:false,lastStatus:'completed'}, 'done', 'Done');
check({runStatus:'completed',lastStatus:'failed',unseen:false}, 'done', 'Done');
check({runStatus:'error',lastStatus:'completed'}, 'needs', 'Needs you', null, 'Run failed');
for(const runStatus of ['interrupted','cancelled','canceled']) check({runStatus,lastStatus:'failed'}, '', '', null, 'Stopped');
const reading = state({...base,question:'Approve?'},null,true);
assert.equal(reading.tone,'working'); assert.equal(reading.detail,'With the Orchestrator');
console.log('Thread state precedence passed: live work, queued, input, background jobs, failures, stopped, review, unread completion and settled, in the shared vocabulary.');
