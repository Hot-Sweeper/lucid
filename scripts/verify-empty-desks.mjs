import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const policy = (await transformWithOxc(await readFile('src/office/room-policy.ts', 'utf8'), 'policy.ts')).code;
const { projectRoomSeats, remainingDeskExtras } = await import('data:text/javascript;base64,' + Buffer.from(policy).toString('base64'));
assert.equal(projectRoomSeats([null], [], true, null, -1).slots, 0);
const job = { id: 'running', runStatus: 'running' };
assert.equal(projectRoomSeats(['running'], [job], true, null, -1).slots, 1);
assert.equal(projectRoomSeats([], [], true, null, 0).slots, 0, 'unused offices do not manufacture starter furniture');
assert.equal(projectRoomSeats([], [], true, null, 1).slots, 1, 'explicit Add a desk still works in an empty room');
assert.equal(remainingDeskExtras(['running',null,null],['running','new',null],2),1,'a new job consumes its spare desk');
assert.equal(remainingDeskExtras(['running','new',null],['running','new',null],1),1,'refresh cannot consume capacity twice');
assert.equal(remainingDeskExtras([],['first'],0),0,'incoming work can create a desk when no spare exists');
assert.equal(remainingDeskExtras([null],['first'],1),0,'first hire uses the explicitly added empty desk');
assert.equal(remainingDeskExtras(['old'],[],2),2,'removing work does not add another spare');
const source = await readFile('src/office/world.ts', 'utf8');
const methods = source.slice(source.indexOf('  canRemoveEmptyDesk('), source.indexOf('  isLastDesk('));
const code = (await transformWithOxc(`class Removal { ${methods} }`, 'remove.ts')).code;
const Removal = new Function(code + ';return Removal')();
const w = new Removal();
w.physicalPlans = [{ id: 'main', slots: 4, threads: [job, null, null, null] }];
w.slotDesks = new Map([['main#0', {threadId:'running'}], ['main#1', {}], ['main#2', {}], ['main#3', {}]]);
w.seats = new Map([['main',['running',null,null,null]]]);w.extra = new Map([['main',3]]);
assert(w.removeEmptyDesk('main#1'), 'non-tail desk can be removed');
assert.deepEqual(w.seats.get('main'), ['running',null,null]);
assert.equal(w.extra.get('main'),2);
assert(!w.removeEmptyDesk('main#0'), 'running work is protected');
w.pendingSeat = {room:'main',index:2};assert(!w.removeEmptyDesk('main#2'), 'launch reservation is protected');
w.pendingSeat = null;w.seats.get('main')[2]='new-job';assert(!w.removeEmptyDesk('main#2'), 'stale menu cannot remove a claimed desk');
assert(!w.removeEmptyDesk('main#99'));
console.log('PASS: any empty desk, starter desk, active jobs, pending launches and stale menus');

const bulk = new Removal();
bulk.physicalPlans=[{id:'main',slots:4,threads:[job,null,null,null]}];
bulk.slotDesks=new Map([['main#0',{threadId:'running'}],['main#1',{}],['main#2',{}],['main#3',{}]]);
bulk.seats=new Map([['main',['running',null,null,null]]]);bulk.extra=new Map([['main',3]]);
assert.equal(bulk.removeEmptyDesks('main'),3,'bulk removes every eligible vacancy once');
assert.deepEqual(bulk.seats.get('main'),['running']);assert.equal(bulk.extra.get('main'),0);
assert.equal(bulk.removeEmptyDesks('other'),0,'cleanup stays in the owning office');
bulk.pendingSeat={room:'main',index:1};assert.deepEqual(bulk.emptyDeskSlots('main'),[],'launching jobs block cleanup');
console.log('PASS: no cloned spares, no automatic starter desks and guarded bulk removal');
