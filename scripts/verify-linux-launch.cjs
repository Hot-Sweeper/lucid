const assert = require('node:assert/strict');
const { displayArgs, gpuArgs, scaleArgs, cursorEnv, VULKAN_ARGS } = require('./launch.cjs');
const fallback = require('../electron/gpu-fallback.cjs');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
assert.deepEqual(displayArgs('linux', {DISPLAY:':0',WAYLAND_DISPLAY:'wayland-1'}, {ozonePlatform:'x11'}), ['--ozone-platform=x11']);
assert.deepEqual(displayArgs('linux', {DISPLAY:':0',WAYLAND_DISPLAY:'wayland-1'}, {ozonePlatform:'wayland'}), ['--ozone-platform=wayland']);
for (const backend of [undefined,'auto','--no-sandbox','x11 --disable-gpu']) assert.deepEqual(displayArgs('linux', {DISPLAY:':0'}, {ozonePlatform:backend}), []);
assert.deepEqual(displayArgs('linux', {WAYLAND_DISPLAY:'wayland-1'}, {ozonePlatform:'x11'}), []);
assert.deepEqual(displayArgs('linux', {DISPLAY:':0'}, {ozonePlatform:'wayland'}), []);
for(const platform of ['win32','darwin']) assert.deepEqual(displayArgs(platform, {DISPLAY:':0'}, {ozonePlatform:'x11'}), []);
// Vulkan only on Linux with X11, only when chosen.
assert.deepEqual(gpuArgs('linux', {gpuBackend:'vulkan'}, ['--ozone-platform=x11']), VULKAN_ARGS);
assert.deepEqual(gpuArgs('linux', {gpuBackend:'vulkan'}, ['--ozone-platform=wayland']), []);
assert.deepEqual(gpuArgs('linux', {gpuBackend:'vulkan'}, []), []);
const x11 = ['--ozone-platform=x11'], xw = {DISPLAY:':0',WAYLAND_DISPLAY:'wayland-1'};
assert.deepEqual(scaleArgs('linux', xw, {}, x11, () => 1.5), ['--force-device-scale-factor=1.5']);
assert.deepEqual(scaleArgs('linux', xw, {uiScale:1.25}, x11, () => 1.5), ['--force-device-scale-factor=1.25']);
assert.deepEqual(scaleArgs('linux', xw, {}, x11, () => 1), []);
assert.deepEqual(scaleArgs('linux', xw, {}, x11, () => null), []);
assert.deepEqual(scaleArgs('linux', {DISPLAY:':0'}, {}, x11, () => 1.5), [], 'plain X11 sessions keep their own scaling');
assert.deepEqual(scaleArgs('linux', xw, {}, ['--ozone-platform=wayland'], () => 1.5), [], 'native Wayland scales itself');
assert.deepEqual(scaleArgs('win32', xw, {}, x11, () => 1.5), []);
assert.deepEqual(cursorEnv(1.5, {}, { size: 32, theme: 'Bibata' }), { XCURSOR_SIZE: '48', XCURSOR_THEME: 'Bibata' }, 'X11 cursor matches the scaled desktop cursor');
assert.deepEqual(cursorEnv(0, {}, { size: 32, theme: 'Bibata' }), {}, 'unscaled launches keep the desktop cursor');
assert.deepEqual(cursorEnv(1.5, { XCURSOR_SIZE: '40' }, { size: 32, theme: 'Bibata' }), {}, 'an explicit cursor size wins');
for (const backend of [undefined,'gl','Vulkan','vulkan --no-sandbox']) assert.deepEqual(gpuArgs('linux', {gpuBackend:backend}, ['--ozone-platform=x11']), []);
assert.deepEqual(gpuArgs('win32', {gpuBackend:'vulkan'}, ['--ozone-platform=x11']), []);
// Fallback: failed status is detected, healthy status is not, and the saved choice flips to OpenGL.
assert.equal(fallback.statusProblem({gpu_compositing:'enabled', vulkan:'enabled_on'}), null);
assert.match(fallback.statusProblem({gpu_compositing:'disabled_software', vulkan:'enabled_on'}), /gpu_compositing/);
assert.match(fallback.statusProblem({gpu_compositing:'enabled', vulkan:'disabled_off'}), /vulkan/);
assert.ok(VULKAN_ARGS.every(fallback.isVulkanArg) && !fallback.isVulkanArg('--ozone-platform=x11'));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lucid-gpu-')), file = path.join(dir, 'lucid', 'launch.json');
fs.mkdirSync(path.dirname(file)); fs.writeFileSync(file, JSON.stringify({ozonePlatform:'x11', gpuBackend:'vulkan'}));
fallback.saveFallback(file, 'GPU process crashed');
const saved = JSON.parse(fs.readFileSync(file, 'utf8'));
assert.equal(saved.gpuBackend, 'gl'); assert.equal(saved.ozonePlatform, 'x11'); assert.equal(saved.gpuFallback.reason, 'GPU process crashed');
assert.deepEqual(gpuArgs('linux', saved, ['--ozone-platform=x11']), []);
fs.rmSync(dir, {recursive:true, force:true});
console.log('PASS: per-app Linux display selection, unavailable-display fallback, platform isolation, fixed flag allowlist, Vulkan selection and OpenGL fallback.');
