import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import electron from 'electron';
const folder=await mkdtemp(join(tmpdir(),'lucid-orchestrator-controls-'));
const evaluation=`(async()=>{
  if(window.__orchControlsCheck)return window.__orchControlsCheck;
  window.__orchControlsCheck={running:true};
  const checks=[],check=(ok,message)=>{if(!ok)throw Error(message);checks.push(message);};
  const wait=ms=>new Promise(r=>setTimeout(r,ms));
  try{
    const orch=window.__orch,world=window.__world;world.update=()=>{};
    if(!orch.state)orch.set({threadId:'__control-test',projectId:'__test',dir:'',review:false,paused:false,reviewWorkflow:1,learned:0,seenUntil:'',lastSentAt:0,reviewed:{}});
    orch.onChange();
    const queue=world.ext.queue;queue.setBoss({id:orch.state.threadId,provider:'codex',running:false});
    const officePower=document.querySelector('#orch-power-toggle'),bar=document.querySelector('.orch-power');
    check(officePower?.getAttribute('role')==='switch'&&!officePower.disabled,'office exposes the global switch directly');
    officePower.click();check(orch.state.paused&&document.querySelector('#orch-power-status').textContent==='Off','direct switch pauses the whole orchestrator');
    officePower.click();check(!orch.state.paused&&document.querySelector('#orch-power-status').textContent==='On','direct switch wakes the orchestrator');
    const visible=()=>{const r=bar.getBoundingClientRect();return r.width>0&&r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;};
    document.querySelector('#side-panel').scrollTop=100000;
    check(visible(),'global switch stays visible after sidebar scrolling');
    document.querySelector('#side-hide').click();await wait(450);
    check(visible()&&!document.querySelector('#side-rail').hidden,'global switch stays visible with folded sidebar');
    document.querySelector('#rail-show').click();await wait(450);
    const shortcut=document.querySelector('#orch-controls-open');
    check(shortcut&&!shortcut.closest('.fold-body'),'orchestrator shortcut is outside collapsed sections');
    shortcut.focus();shortcut.click();
    const dialog=document.querySelector('.orch-controls'),presence=dialog.querySelector('[data-presence]'),review=dialog.querySelector('[data-review]'),enabled=dialog.querySelector('[data-enabled]');
    check(document.activeElement===enabled,'dialog focuses global on/off switch');
    const change=(el,value)=>{el.value=value;el.dispatchEvent(new Event('change'));};
    const power=on=>{enabled.checked=on;enabled.dispatchEvent(new Event('change'));};
    power(false);
    change(presence,'sleep');check(orch.state.paused&&queue.boss.w.activity==='nap','sleep pauses automation and robot naps');
    change(presence,'away');check(orch.state.paused&&!queue.boss.w,'away pauses automation and leaves chair empty');
    power(true);check(!orch.state.paused&&queue.boss.w,'global on restores robot at the desk');
    change(review,'manual');check(!orch.state.review&&dialog.textContent.includes('You decide'),'manual report review remains with the user');
    power(false);change(review,'auto');check(orch.state.review&&orch.state.paused,'automatic review preference cannot bypass global off');
    power(true);change(review,'manual');
    const answers=dialog.querySelector('[data-answers]');answers.checked=false;answers.dispatchEvent(new Event('change'));check(orch.state.auto===false,'question delegation is independently controllable');
    await wait(150);const saved=JSON.parse(window.lucid.settingsLoad());check(saved.orch.review===false&&saved.orch.auto===false&&saved.orch.presence==='awake','controls persist to settings');
    const bounds=dialog.getBoundingClientRect();check(bounds.left>=0&&bounds.right<=innerWidth&&bounds.top>=0&&bounds.bottom<=innerHeight,'controls fit viewport');
    window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));check(!document.querySelector('.orch-controls')&&document.activeElement===shortcut,'Escape closes only controls and restores focus');
    shortcut.click();document.querySelector('[data-reports]').click();await wait(150);check(!!document.querySelector('.paper-search'),'review reports opens the manual report archive');
    document.querySelectorAll('.dialog-wrap').forEach(el=>el.remove());shortcut.click();const off=document.querySelector('[data-enabled]');off.checked=false;off.dispatchEvent(new Event('change'));
    window.__orchControlsCheck={ok:true,checks};
  }catch(error){window.__orchControlsCheck={ok:false,error:String(error),stack:error.stack,checks};}
  return window.__orchControlsCheck;
})()`;
const file=join(folder,'evaluation.js');await writeFile(file,evaluation);
const env={...process.env,LUCID_SHOT:folder,LUCID_SHOT_PROFILE:join(folder,'profile'),LUCID_SHOT_COUNT:'3',LUCID_SHOT_EVERY:'3000',LUCID_SHOT_QUIT:'1',LUCID_EVAL_FILE:file};
delete env.ELECTRON_RUN_AS_NODE;delete env.LUCID_EVAL;
await new Promise((resolve,reject)=>{const child=spawn(electron,['.'],{env,stdio:'inherit'});child.on('error',reject);child.on('exit',code=>code===0?resolve():reject(Error('Electron exited '+code)));});
const log=await readFile(join(folder,'eval.log'),'utf8');console.log('Artifacts: '+folder);console.log(log);
assert(log.includes('"ok": true')&&!log.includes('"ok": false'),'orchestrator native controls pass');
