import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { transformWithOxc } from "vite";
const code = (await transformWithOxc(await readFile(new URL("../src/office/exposed-scene.ts", import.meta.url), "utf8"), "exposed-scene.ts")).code.replace(/^export /gm, "").replace(/export\s*\{[^}]*\};?/g, "");
const exposedScene = new Function(`${code};return exposedScene`)();
const box = (left, right, top=40, bottom=900) => ({left,right,top,bottom});
const scene=box(300,1400);
assert.deepEqual(exposedScene(scene,[box(0,300),box(1400,1900)]),{left:0,right:0},"Docked sidebars are already excluded");
assert.deepEqual(exposedScene(scene,[box(0,400),box(1300,1900)]),{left:100,right:100},"Overlapping sidebars become the entry edges");
assert.deepEqual(exposedScene(scene,[box(0,364),box(1336,1900)]),{left:64,right:64},"Collapsed rails still hide travel");
assert.deepEqual(exposedScene(scene,[box(0,0),box(0,450,0,0),box(1350,1900,800,900)]),{left:0,right:0},"Hidden panels and floating controls do not obscure the whole edge");
assert.deepEqual(exposedScene(box(400,1500),[box(0,450),box(1400,1900)]),{left:50,right:100},"Window offsets stay in scene coordinates");
assert.deepEqual(exposedScene(scene,[box(0,450),box(0,400),box(1350,1900)]),{left:150,right:50},"Panel overlap is not counted twice");
assert.deepEqual(exposedScene(scene,[box(0,300),box(1000,1900)]),{left:0,right:400},"Resizing a conversation updates its edge");
console.log("Exposed scene: docked and overlapping sidebars, collapsed/hidden rails, resizing, offsets and floating controls passed.");
