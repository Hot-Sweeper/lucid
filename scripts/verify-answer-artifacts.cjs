const assert = require('node:assert/strict');
const { DatabaseSync } = require('node:sqlite');
const { answerArtifacts } = require('../electron/answer-artifacts.cjs');
const { robotMode } = require('../electron/robot-mode.cjs');
const db = new DatabaseSync(':memory:');
db.exec('create table orchestration_v2_projection_turn_items(turn_item_id,thread_id,type,status,updated_at,ordinal,payload_json)');
const insert = db.prepare('insert into orchestration_v2_projection_turn_items values(?,?,?,?,?,?,?)');
const at='2026-11-08T12:00:00Z';
const real = {toolName:'t3-code.html_render',input:{html:'<img src="/tmp/effort-pixels.png">'},output:{htmlRender:{attachmentId:'actual-html',title:'Actual visual',height:464}}};
insert.run('one','t','dynamic_tool','completed',at,1,JSON.stringify(real));
insert.run('log','t','dynamic_tool','completed',at,2,JSON.stringify({toolName:'exec',output:'<html>Private log</html>'}));
insert.run('foreign','other','dynamic_tool','completed',at,3,JSON.stringify(real));
assert.equal(answerArtifacts(db,'t').length,1);
assert.equal(answerArtifacts(db,'t')[0].artifact.html,real.input.html);
assert.equal(answerArtifacts(db,'t',{since:'2026-11-09'}).length,0);
assert.equal(answerArtifacts(db,'t',{before:'2026-11-07'}).length,0);
for(const effort of ['ultra','ultracode','max','xhigh']) assert.equal(robotMode({options:[{id:'reasoningEffort',value:effort}]}).ultra,true);
for(const effort of ['high','medium','low','off','']) assert.equal(robotMode({options:{effort}}).ultra,false);
assert.deepEqual(robotMode({options:{effort:'ultracode',fastMode:true}}),{effort:'ultracode',ultra:true,fast:true});
assert.equal(robotMode({options:[{id:'serviceTier',value:'priority'}]}).fast,true);
assert.equal(robotMode({model:'grok-code-fast',options:{fastMode:false,serviceTier:'default'}}).fast,false);
console.log('PASS: explicit persisted HTML visuals, page bounds, environment isolation and actual effort/speed options.');
