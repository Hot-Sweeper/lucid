const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createReports, parseVerdict } = require('../electron/reports.cjs');
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'lucid-report-check-'));
(async () => {
  let settings = { threadId: 'boss', review: true, paused: true };
  let pinned = false;
  let run = 'run-1', pendingRuns = 0, settled = false, replies = [], failSettlement = false;
  const sends = [], settlements = [];
  const image = path.join(folder, 'before.png'); fs.writeFileSync(image, Buffer.from('test-image-before'));
  const after = path.join(folder, 'after.png'); fs.writeFileSync(after, Buffer.from('test-image-after'));
  const facts = () => ({ pinned, title: 'Fix layout', provider: 'codex', model: 'model', effort: 'high', team: [{ threadId: 'worker', provider: 'codex', model: 'model', effort: 'high', runIds: ['one'], role: 'Owner' }], projectTitle: 'Lucid', originalRequest: 'Fix the layout', run: { id: run, status: 'completed' }, pendingRuns, pendingRequests: 0, settled, children: [{ id: 'child', title: 'Check layout' }], sessions: [], messages: [{ role: 'assistant', text: `Changed layout. ![Before](${image}) ![After](${after})`, attachments: [] }] });
  const dependencies = { dir: path.join(folder, 'archive'), settings: () => settings, t3: { reportFacts: facts, repliesSince: () => ({ messages: replies }), sendMessage: async m => { sends.push(m); } }, server: { settleThread: async id => { if (failSettlement) throw Error('T3 offline'); settlements.push(id); settled = true; }, unsettleThread: async () => { settled = false; } }, usage: { getSessionUsage: async () => ({ available: false, tokens: null, costUsd: null }) } };
  let service = createReports(dependencies);
  pendingRuns = 1; assert.equal(await service.submit('worker'), null, 'queued or child work prevents submission'); pendingRuns = 0;
  const p = await service.submit('worker', { id: 'robot', name: 'Mochi', provider: 'codex' });
  assert.equal(p.effort, 'high'); assert.equal(p.team[0].model, 'model'); assert.equal(p.team[0].effort, 'high'); assert.equal(p.team[0].robot.name, 'Mochi');
  assert.equal(p.robot.name, 'Mochi'); assert.equal(p.children.length, 1); assert.equal(p.images.length, 2);
  assert.equal((await service.submit('worker')).id, p.id); assert.equal(service.list().length, 1, 'run submissions deduplicate');
  p.verdict = { humanChecks: [{ question: 'Can you hear your microphone recording?', instructions: 'Record and play back a short phrase.' }] };
  await service.manual(p.id, 'human-answer', { index: 0, answer: 'no' });
  assert.equal(createReports(dependencies).list()[0].humanAnswers[0].answer, 'no', 'human answers survive restart');
  await assert.rejects(service.manual(p.id, 'human-answer', { index: 9, answer: 'yes' }));
  fs.unlinkSync(image); assert(fs.existsSync(p.images[0].path), 'screenshot snapshot survives deletion of original');
  await service.tick(['worker']); assert.equal(sends.length, 0, 'pause holds delivered reports');
  service = createReports(dependencies); assert.equal(service.list()[0].delivered, true, 'queue survives restart'); assert.equal(service.list()[0].team[0].effort, 'high', 'execution identity survives restart');
  settings.paused = false; await service.tick(); assert.equal(sends.length, 1); assert.equal(service.list()[0].status, 'reviewing');
  replies = [{ text: JSON.stringify({ report: 'wrong', decision: 'approve' }), streaming: false }];
  await service.tick(); assert.equal(settlements.length, 0, 'wrong report cannot settle a task');
  replies = [{ text: JSON.stringify({ report: p.id, decision: 'approve', summary: 'Layout verified', visualChanged: true, checks: ['Layout checks pass'], before: [image], after: [after] }), streaming: false }];
  settings.paused = true; await service.tick(); assert.equal(settlements.length, 0, 'pause blocks an in-flight verdict');
  settings.paused = false; await service.tick(); assert.equal(settlements.length, 1); assert.equal(service.list()[0].status, 'settled');
  assert(service.list()[0].history.some(h => h.action === 'Settled in T3'));
  await service.tick(); assert.equal(settlements.length, 1, 'settlement does not repeat');
  await service.manual(p.id, 'reopen'); assert.equal(settled, false);
  run = 'run-2'; const revised = await service.submit('worker', { name: 'Mochi' }); assert.equal(service.list().length, 2, 'revisions keep old papers');
  await service.manual(revised.id, 'approve', { summary: 'Visual update', visualChanged: true, checks: ['Verified'] });
  assert.equal(service.list()[0].status, 'manual-review'); assert.match(service.list()[0].error, /Before and after/);
  assert.equal(settlements.length, 1, 'missing evidence prevents settlement');
  revised.orchestratorId = 'boss'; revised.sentAt = new Date().toISOString(); revised.history.push({by:'Orchestrator',action:'Review: manual'});
  failSettlement = true;
  await assert.rejects(service.manual(revised.id, 'approve', { summary: 'Logic only', visualChanged: false, checks: ['Unit tests pass'] }), /offline/);
  assert.equal(service.list()[0].status, 'approved', 'approval survives transport failure');
  failSettlement = false; await service.tick(); assert.equal(service.list()[0].status, 'settled', 'approved intent recovers without another model call');
  settled = false; run = 'run-3'; const next = await service.submit('worker');
  settings.paused = true;
  await service.manual(next.id, 'changes', { summary: 'Fix the remaining issue' });
  assert.equal(next.status, 'changes-requested'); assert.match(sends.at(-1).message, /Fix the remaining issue/);
  run = 'run-4'; const stale = await service.submit('worker'); run = 'run-5'; settings.paused = false; await service.tick(['worker']);
  assert.equal(stale.status, 'superseded', 'new work invalidates old approvals');
  assert.equal(parseVerdict('```json\n{"report":"paper","decision":"manual"}\n```').report, 'paper');
  assert.equal(parseVerdict('No structured verdict.'), null);
  const count = service.list().length;
  pinned = true; run = 'manager';
  assert.equal(await service.submit('manager'), null, 'pinned project managers cannot submit');
  assert.equal(service.list().length, count);
  pinned = false; run = 'promoted-during-snapshot';
  const getUsage = dependencies.usage.getSessionUsage;
  dependencies.usage.getSessionUsage = async () => { pinned = true; return { available: false }; };
  assert.equal(await service.submit('worker'), null, 'promotion during snapshot also blocks submission');
  dependencies.usage.getSessionUsage = getUsage;
  pinned = false; run = 'promoted-during-review'; replies = [];
  const manager = await service.submit('worker'); await service.tick(['worker']);
  const beforeCount = settlements.length;
  replies = [{ streaming: false, text: JSON.stringify({ report: manager.id, decision: 'approve', summary: 'Checked', visualChanged: false, checks: ['Tests pass'] }) }];
  pinned = true; await service.tick();
  assert.equal(manager.status, 'manager-excluded'); assert.equal(settlements.length, beforeCount, 'promotion during review prevents settlement');
  pinned = false; run = 'promoted-before-dispatch'; replies = [];
  const lastMoment = await service.submit('worker'); await service.tick(['worker']);
  replies = [{ streaming: false, text: JSON.stringify({ report: lastMoment.id, decision: 'approve', summary: 'Checked', visualChanged: false, checks: ['Tests pass'] }) }];
  // Re-read manager status after the approval is persisted, immediately before dispatch.
  pinned = false;
  dependencies.t3.reportState = () => { if (service.list()[0].status === 'approved') pinned = true; return facts(); };
  service = createReports(dependencies);
  await service.tick();
  assert.equal(service.list()[0].status, 'manager-excluded'); assert.equal(settlements.length, beforeCount, 'promotion immediately before dispatch prevents settlement');
  // Exercise the native bridge's connect-then-check ordering with an isolated transport.
  const source = fs.readFileSync(require.resolve('../electron/t3server.cjs'), 'utf8');
  const fn = source.slice(source.indexOf('async function settleThread('), source.indexOf('function unsettleThread('));
  let dispatches = 0, promoted = false;
  const vm = require('node:vm');
  const ctx = { connect: async () => { promoted = true; }, require: () => ({ reportState: () => ({ pinned: promoted }) }), dispatch: () => { dispatches++; }, T3ServerError: class extends Error { constructor(m, code) { super(m); this.code = code; } } };
  vm.runInNewContext(fn + ';this.settle = settleThread', ctx);
  await assert.rejects(ctx.settle('worker', { excludePinned: true }), e => e.code === 'manager-protected');
  assert.equal(dispatches, 0, 'promotion during connection cannot reach settlement dispatch');

  // Dependency reviews must not wake the source worker or resubmit acknowledgment runs.
  let heldRun = 'held-1', heldSettled = false, heldReplies = [];
  const heldSends = [];
  const heldFacts = () => ({ ...facts(), pinned: false, settled: heldSettled, run: { id: heldRun, status: 'completed' }, pendingRuns: 0, pendingRequests: 0 });
  const heldDependencies = { ...dependencies, dir: path.join(folder, 'dependency-archive'),
    t3: { reportFacts: heldFacts, reportState: heldFacts, repliesSince: () => ({ messages: heldReplies }), sendMessage: async m => heldSends.push(m) } };
  let heldService = createReports(heldDependencies);
  const held = await heldService.submit('dependent');
  await heldService.tick();
  assert.equal(held.status, 'reviewing');
  heldReplies = [{ text: JSON.stringify({ report: held.id, decision: 'pending', summary: 'Await coordinated stabilization delivery proof' }), streaming: false }];
  await heldService.tick();
  assert.equal(held.status, 'pending-dependency');
  assert.equal(heldSends.length, 1, 'pending sends no source worker acknowledgment request');
  const imageHashes = held.images.map(i => i.hash);
  heldService = createReports(heldDependencies);
  heldRun = 'acknowledgment-run';
  await heldService.tick();
  assert.equal(await heldService.submit('dependent'), null, 'new completion cannot bypass persisted dependency hold');
  assert.equal(heldSends.length, 1, 'restart and polling do not dispatch another review');
  assert.deepEqual(heldService.list()[0].images.map(i => i.hash), imageHashes, 'accepted artifacts survive hold');
  await heldService.manual(held.id, 'retry');
  await heldService.tick();
  assert.equal(heldService.list()[0].status, 'superseded', 'retry uses current run rather than accepting stale evidence');
  const resumed = await heldService.submit('dependent');
  assert(resumed && resumed.runId === heldRun, 'explicit retry admits a current submission');
  await heldService.manual(resumed.id, 'pending', { summary: 'Still waiting' });
  heldSettled = true;
  await heldService.tick();
  assert.equal(resumed.status, 'settled', 'real external settlement remains authoritative during hold');

  console.log('Report checks passed: persistence, screenshots, pause, backlog, child work, matching verdicts, settlement, reopening, missing evidence, transport recovery, revisions, feedback stale-run protection, and manager promotion exclusions.');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => {
  const resolved = path.resolve(folder), tempRoot = path.resolve(os.tmpdir()) + path.sep;
  if (!resolved.startsWith(tempRoot) || !path.basename(resolved).startsWith('lucid-report-check-')) throw Error('Unexpected cleanup path');
  fs.rmSync(resolved, { recursive: true, force: true });
});
