import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const compile = async (source, name) => (await transformWithOxc(source, name)).code;
const source = await readFile(new URL('../src/remote-client.ts', import.meta.url), 'utf8');
const remote = await import('data:text/javascript;base64,' + Buffer.from(await compile(source, 'remote-client.ts')).toString('base64'));
const { mergeCompanionCommit, installCompanionOwner } = remote;
const json = JSON.stringify;
const settings = { ui: { sideW: 410 }, wallet: { spent: 20 }, hidden: [], roles: [] };
const change = { kind: 'settings', before: json(settings), after: json({ ...settings, hidden: ['p:a'] }) };
assert.deepEqual(JSON.parse(mergeCompanionCommit(json({ ...settings, wallet: { spent: 21 }, ui: { sideW: 420 } }), change)), { ...settings, wallet: { spent: 21 }, ui: { sideW: 420 }, hidden: ['p:a'] }, 'a phone edit preserves newer desktop wallet and layout');
assert.throws(() => mergeCompanionCommit(json({ ...settings, hidden: ['p:b'] }), change), /changed on the computer/, 'conflicting edits reject instead of overwriting');
assert.doesNotThrow(() => mergeCompanionCommit(json({ ...settings, hidden: ['p:a'] }), change), 'retrying an already applied action is idempotent');
assert.throws(() => mergeCompanionCommit(json(settings), { ...change, after: json({ ...settings, wallet: { spent: 0 } }) }), /on the computer/, 'generic companion writes cannot duplicate wallet collection');
const robot = { id: 'robot-1', name: 'Pip', look: { hat: 'cap' }, threadId: 'thread-1', jobs: 4 };
const appearance = { kind: 'roster', before: json([robot]), after: json([{ ...robot, name: 'Bolt' }]) };
const updated = { ...robot, jobs: 5, threadId: 'thread-2', look: { hat: 'crown' } };
assert.deepEqual(JSON.parse(mergeCompanionCommit(json([updated]), appearance)), [{ ...updated, name: 'Bolt' }], 'renaming preserves newer assignments, history and unchanged appearance');
assert.throws(() => mergeCompanionCommit(json([{ ...robot, name: 'Mochi' }]), appearance), /changed on the computer/);
assert.throws(() => mergeCompanionCommit(json([robot]), { ...appearance, after: json([]) }), /removed on the computer/);
assert.throws(() => mergeCompanionCommit(json([robot]), { ...appearance, after: json([robot, { ...robot, id: 'clone' }]) }), /creates new robots/);
assert.throws(() => mergeCompanionCommit(json([robot]), { ...appearance, after: json([{ ...robot, threadId: 'different' }]) }), /Assign this robot/);
globalThis.window = { lucidRemote: false };
let state = { settings: json(settings), roster: json([robot]) }, simultaneous = 0, max = 0;
installCompanionOwner({ snapshot: () => ({ ...state }), apply: async (kind, value) => { max = Math.max(max, ++simultaneous); await Promise.resolve(); state[kind] = value; simultaneous--; }, hire: async () => {} });
const owner = window.__lucidCompanion;
await Promise.all([owner.commit(change), owner.commit({ kind: 'settings', before: json(settings), after: json({ ...settings, roles: [{ name: 'Reviewer', brief: 'Review.' }] }) })]);
assert.equal(max, 1, 'desktop applies companion mutations serially');
assert.deepEqual(JSON.parse(state.settings).hidden, ['p:a']);
assert.equal(JSON.parse(state.settings).roles.length, 1, 'queued mutations merge against latest authoritative state');
await assert.rejects(owner.commit({ ...change, after: json({ ...settings, hidden: ['p:conflict'] }) }), /changed on the computer/);
await owner.commit(appearance);
assert.equal(JSON.parse(state.roster)[0].name, 'Bolt', 'a rejected action does not block the next action');

