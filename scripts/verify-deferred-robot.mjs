import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {transformWithOxc} from 'vite';
const result=await transformWithOxc(await fs.readFile(new URL('../src/perf/deferred-robot.ts',import.meta.url),'utf8'),'deferred-robot.ts');
const {DeferredRobot}=await import('data:text/javascript;base64,'+Buffer.from(result.code).toString('base64'));
let created=0,active=0,destroyed=0;const calls=[];
const host={empty:true};
const factory=()=>{const id=++created;active++;return new Proxy({el:{id},brandName:'codex',currentPose:'rest',destroy(){active--;destroyed++}}, {get(target,key){return target[key]??((...args)=>{calls.push([id,key,...args]);return ['drink','holdPhone'].includes(key)?Promise.resolve():undefined})}})};
const robot=new DeferredRobot(host,factory);
robot.setPose('rest');robot.setLook({hat:'cap'});await robot.holdPhone(false);
assert.equal(created,0,'free desks must not materialize character SVG or animation loops');
assert.equal(robot.el,host);
const first=robot.mount();assert.equal(robot.mount(),first,'repeated assignment must retain one rig');
robot.setBrand('claudeAgent');robot.setLook({hat:'cap'});robot.setModel('gpt-6.1-sol');robot.thumbAt(.2,.8);robot.setGroove(120);await robot.holdPhone(true);
assert.ok(calls.some(c=>c[1]==='thumbAt'&&c[2]===.2&&c[3]===.8),'phone keyboard thumb positioning still reaches the actual rig');
assert.ok(calls.some(c=>c[1]==='setLook'),'customization reaches the mounted rig');
assert.equal(active,1);
robot.destroy();robot.destroy();assert.equal(active,0);assert.equal(destroyed,1,'unassignment releases animation ownership exactly once');
robot.wake();robot.setPose('rest');assert.equal(created,1,'computer reset on an empty desk must not recreate its character');
robot.mount();assert.equal(active,1);assert.equal(created,2,'reassignment creates exactly one fresh rig');
assert.equal(robot.el.id,2);robot.destroy();assert.equal(active,0);assert.equal(destroyed,2);
console.log('PASS: empty desk construction/reset, single mount, customization/phone forwarding, idempotent release and clean reassignment');
