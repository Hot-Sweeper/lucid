const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { stripTypeScriptTypes } = require('node:module');
const context = { structuredClone, Date, console };
const ledger = fs.readFileSync('src/office/coin-ledger.ts', 'utf8').replace(/export /g, '');
vm.runInNewContext(stripTypeScriptTypes(ledger, { mode: 'transform' }) + '\nglobalThis.coinApi={startCoinLedger,observeCoinLedger,collectCoinJob,collectible};', context);
const { startCoinLedger, observeCoinLedger, collectCoinJob, collectible } = context.coinApi;
const source = (costUsd, status = 'completed', key = 'codex:s1', threadId = 't1') => ({ key, threadId, title: 'A real task', status, costUsd });
let state = startCoinLedger([source(10), source(null, 'completed', 'codex:missing')], 50);
observeCoinLedger(state, [source(11, 'running')], 1.5);
assert.equal(collectible(state.jobs.t1), 0, 'running robots cannot be collected');
observeCoinLedger(state, [source(11)], 1);
assert.equal(collectible(state.jobs.t1), 1.5, 'completion exposes the accrued coins');
assert.equal(collectCoinJob(state, 't1').coins, 1.5);
assert.equal(collectCoinJob(state, 't1'), null, 'double click does not duplicate payout');
state = JSON.parse(JSON.stringify(state));
observeCoinLedger(state, [source(11), source(8), source(11), source(30, 'completed', 'codex:missing')], 1);
assert.equal(collectCoinJob(state, 't1'), null, 'reload, repeat, shrinking logs and late prices cannot repay history');
observeCoinLedger(state, [source(11.25)], 1);
assert.equal(collectCoinJob(state, 't1').coins, .25, 'late final usage remains collectible');
observeCoinLedger(state, [source(.004, 'completed', 'codex:new')], 1);
assert.equal(collectCoinJob(state, 't1'), null);
observeCoinLedger(state, [source(.011, 'completed', 'codex:new')], 1);
assert.equal(collectCoinJob(state, 't1').coins, .01);
assert.equal(state.jobs.t1.coins, .001, 'fractional residue is preserved');
observeCoinLedger(state, [source(.031, 'failed', 'codex:new')], 1);
assert.equal(collectCoinJob(state, 't1'), null, 'failed work is not presented as complete');

const walletFile = fs.readFileSync('src/office/wallet.ts', 'utf8');
const walletSource = walletFile.slice(walletFile.indexOf('export const COINS_PER_DOLLAR'), walletFile.indexOf('export const coinIcon')).replace(/export /g, '');
const walletContext = { structuredClone, Date, console, startCoinLedger, observeCoinLedger, collectCoinJob, collectible, roundCoins: n => Math.round(n * 1e6) / 1e6 };
vm.runInNewContext(stripTypeScriptTypes(walletSource, { mode: 'transform' }) + '\nglobalThis.Wallet=Wallet;', walletContext);
let saved = { v: 2, ledger: { welcome: 40.75, 'bonus:daily:old': 5, '2026-10-31': 2.8 }, spent: 8, owned: ['floor:oak'], daily: { last: '2026-10-31', streak: 2 } };
let wallet = new walletContext.Wallet(() => saved, s => { saved = s; });
const balance = wallet.balance;
wallet.observeSources([source(12)]);
assert.equal(wallet.balance, balance, 'migration preserves the exact previous balance');
assert.equal(saved.spent, 8); assert.equal(saved.owned[0], 'floor:oak', 'older saved fields stay intact');
wallet.observe({ windows: { today: { costUsd: 100 }, week: { costUsd: 200 } } });
assert.equal(wallet.balance, balance, 'global usage no longer auto-credits collection earnings');
assert.equal(saved.daily.streak, 2, 'no daily reward is paid');
wallet.observeSources([source(14.25)]);
assert.equal(wallet.rewards[0].amount, 2.25, 'coins match the dollars the work cost');
assert.equal(wallet.balance, balance, 'pending rewards are not counted yet');
assert.equal(wallet.collect('t1'), 2.25); assert.equal(wallet.collect('t1'), 0);
assert.equal(wallet.balance, balance + 2.25);
wallet = new walletContext.Wallet(() => saved, s => { saved = s; });
wallet.observeSources([source(14.25)]);
assert.equal(wallet.rewards.length, 0, 'reload does not repay collected work');
console.log('PASS: coin ledger high-water marks, completion, fractional coins, retries, reload, no double collection, wallet migration and preserved saved data.');
