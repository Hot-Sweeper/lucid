import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const source = await readFile(new URL('../../src/harness/layout.ts', import.meta.url), 'utf8');
const code = (await transformWithOxc(source, 'layout.ts')).code.replace(/export\s*\{[^}]*\};?/g, '').replace(/^export /gm, '');
const frames = [], events = [], errors = [];
const schedule = new Function('requestAnimationFrame', 'reportError', `${code};return scheduleLayout`)(fn => (frames.push(fn), frames.length), e => errors.push(e));
const a = { isConnected: true }, b = { isConnected: true }, gone = { isConnected: false };
schedule(a, () => { events.push('obsolete'); return null; });
schedule(a, () => { events.push('read-a'); return () => events.push('write-a'); });
schedule(b, () => { events.push('read-b'); return () => events.push('write-b'); });
schedule(gone, () => { events.push('detached'); return null; });
assert.equal(frames.length, 1); frames.shift()();
assert.deepEqual(events, ['read-a', 'read-b', 'write-a', 'write-b']);
events.length = 0;
schedule(a, () => { events.push('read-a'); b.isConnected = false; return () => events.push('write-a'); });
schedule(b, () => { events.push('detached-b'); return null; }); frames.shift()();
assert.deepEqual(events, ['read-a', 'write-a']);
schedule(a, () => { throw Error('fixture'); }); frames.shift()(); assert.equal(errors.length, 1);
schedule(a, () => () => events.push('recovered')); frames.shift()(); assert.equal(events.at(-1), 'recovered');
console.log('PASS: coalesced jobs, all geometry reads before writes, disconnected owners, and error recovery');
