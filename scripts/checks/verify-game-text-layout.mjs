import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { transformWithOxc } from 'vite';
const { code } = await transformWithOxc(await fs.readFile(new URL('../../src/games/text-layout.ts', import.meta.url), 'utf8'), 'text-layout.ts');
const { textLayout } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
let measured = 0, unit = 6;
const ctx = { font: '600 12px Lexend', measureText(text) { measured++; return { width: text.length * unit }; } };
const layout = textLayout();
const first = layout.get(ctx, 'A rubber chicken with a pulley in the middle.', 100);
assert.deepEqual(first.lines, ['A rubber chicken', 'with a pulley in', 'the middle.']);
assert.equal(first.width, 96);
const initialMeasurements = measured;
for (let i = 0; i < 240; i++) assert.equal(layout.get(ctx, 'A rubber chicken with a pulley in the middle.', 100), first);
assert.equal(measured, initialMeasurements, 'a moving speaker must not measure or wrap unchanged dialogue each frame');
const changed = layout.get(ctx, 'That is heavier than it looks.', 100);
assert.notEqual(changed, first);
const wider = layout.get(ctx, 'That is heavier than it looks.', 220);
assert.notDeepEqual(wider.lines, changed.lines, 'a width change must reflow the same dialogue');
ctx.font = '600 14px Lexend'; unit = 7;
const changedFont = layout.get(ctx, 'That is heavier than it looks.', 220);
assert.equal(changedFont.width, 210, 'font changes must replace stale text measurements');
const beforeLoad = measured;
unit = 8; layout.clear();
const loaded = layout.get(ctx, 'That is heavier than it looks.', 220);
assert.ok(measured > beforeLoad, 'finishing font loading must invalidate fallback font measurements');
assert.ok(loaded.width <= 220);
assert.deepEqual(layout.get(ctx, '', 220), { lines: [], width: 0 });
console.log('PASS: stationary text is measured once; dialogue, width, font and font-load changes reflow correctly');
