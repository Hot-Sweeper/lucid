const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const { hireDefaults, launchPayload } = require('../../electron/hire-runtime.cjs');
const selection = { instanceId: 'codex', model: 'sol', options: [{ id: 'reasoningEffort', value: 'high' }, { id: 'fast', value: false }] };
const settings = { defaultModelSelection: selection, defaultRuntimeMode: 'auto', projectSettingsFolded: true };
