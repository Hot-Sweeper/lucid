import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';
const source = await readFile(new URL('../../src/office/history-window.ts', import.meta.url), 'utf8');
const code = (await transformWithOxc(source, 'history-window.ts')).code.replace(/^export /gm, '').replace(/export\s*\{[^}]*\};?/g, '');
const { HistoryWindow } = new Function(`${code};return {HistoryWindow}`)();
const m = (n, text = `Message ${n}`) => ({ id: `m${n}`, at: '2026-10-31T12:00:00Z', role: 'assistant', sourceOrder: n, text });
const page = (a, b, more = true) => ({ messages: Array.from({ length: b - a }, (_, i) => m(a + i)), cursor: { at: m(a).at, rowid: a }, hasMore: more });
const history = new HistoryWindow();
history.update(page(125, 205));
history.update(page(126, 206)); // Equal-time rows rolling out of latest are retained.
assert.equal(history.cursor.rowid, 125, 'live refresh must not shift the older cursor');
const slow = page(45, 125);
slow.messages.push(m(204, 'stale stream'));
history.update({ ...page(126, 206), messages: [...page(126, 206).messages.filter(x => x.id !== 'm204'), m(204, 'new stream')] });
let rows = history.update(slow, true);
assert.equal(rows.find(x => x.id === 'm204').text, 'new stream');
rows = history.update(page(0, 45, false), true);
assert.deepEqual(rows.map(x => x.id), Array.from({ length: 206 }, (_, n) => `m${n}`));
assert.equal(history.hasMore, false);
const latest = page(126, 206).messages.filter(x => x.id !== 'm190');
latest.push({ id: 'queued', at: '2026-01-01', role: 'user', run: 'queued' });
rows = history.update({ messages: latest, cursor: null, hasMore: true });
assert.ok(!rows.some(x => x.id === 'm190'), 'source-deleted recent message must disappear');
rows = history.update({ messages: latest.filter(x => x.id !== 'queued'), cursor: null, hasMore: true });
assert.ok(!rows.some(x => x.id === 'queued'), 'departed queued message must disappear');
rows = history.update({ messages: [{ id: 'queued', at: '2026-01-01', role: 'user', run: 'queued' }], cursor: null, hasMore: false }, true);
assert.ok(!rows.some(x => x.id === 'queued'), 'late older-page response must not resurrect a departed queued prompt');
assert.ok(rows.some(x => x.id === 'm0'), 'loaded older messages stay available on latest refresh');
assert.equal(history.hasMore, false);
const panel = await readFile(new URL('../../src/office/chat-panel.ts', import.meta.url), 'utf8');
assert.match(panel, /generation !== this\.historyGeneration/);
assert.match(panel, /this\.renderHistory\(this\.history\.update\(page, true\), true\)/);
assert.match(panel, /anchor\.getBoundingClientRect\(\)\.top - anchorY/);
console.log('History window passed: equal timestamps, bounded refresh, slow-stream protection, queue/deletion state, older-page retention and guarded scroll restoration.');
