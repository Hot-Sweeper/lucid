import { readFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import vm from "node:vm";
import assert from "node:assert/strict";
const code = stripTypeScriptTypes(readFileSync(new URL("../../src/os/uac.ts", import.meta.url), "utf8").replace(/^import .*;\r?\n/gm, ""), { mode: "transform" })
  .replace(/^export /gm, "") + "\nglobalThis.UacPrompt = UacPrompt;";
const context = { window: { clearInterval() {} }, gsap: {}, esc: value => value };
vm.runInNewContext(code, context);
const wm = { epoch: 1 };
let resolvePending, shown = 0;
const prompt = new context.UacPrompt(wm, { pending: () => new Promise(resolve => { resolvePending = resolve; }) });
prompt.show = () => { shown++; };
const load = prompt.sync("old-thread", "old", { name: "Old robot", harness: "Codex" });
prompt.reset(); resolvePending([{ id: "old", type: "approval" }]); await load;
assert.equal(shown, 0, "a reset invalidates an in-flight prompt even without an epoch change");
const epochLoad = prompt.sync("old-thread", "old", { name: "Old robot", harness: "Codex" });
wm.epoch++; resolvePending([{ id: "old", type: "approval" }]); await epochLoad;
assert.equal(shown, 0, "a reassigned desk never shows the previous thread's prompt");
let resolveOutcome, settled = 0;
prompt.deps = { pending: async () => [], outcome: () => new Promise(resolve => { resolveOutcome = resolve; }) };
prompt.id = "old"; prompt.el = { remove() {} }; prompt.epoch = wm.epoch;
prompt.settle = () => { settled++; };
const poll = prompt.poll("old-thread"); await new Promise(setImmediate);
assert.equal(typeof resolveOutcome, "function");
prompt.reset(); prompt.id = "new"; prompt.el = { remove() {} };
resolveOutcome({ status: "resolved", decision: "accept" }); await poll;
assert.equal(settled, 0, "an old outcome cannot press or clear a newer request");
console.log("PASS: stale pending reads and recorded approval outcomes cannot leak across desk resets or requests");
