import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {transformWithOxc} from 'vite';
const result=await transformWithOxc(await fs.readFile(new URL('../src/perf/svg-write.ts',import.meta.url),'utf8'),'svg-write.ts');
const {setSvgAttribute}=await import('data:text/javascript;base64,'+Buffer.from(result.code).toString('base64'));
const attrs=new Map(),writes=[];
const el={getAttribute:name=>attrs.get(name)??null,setAttribute:(name,value)=>{attrs.set(name,value);writes.push([name,value])}};
setSvgAttribute(el,'transform','translate(10 20)');
for(let i=0;i<120;i++)setSvgAttribute(el,'transform','translate(10 20)');
assert.equal(writes.length,1,'a steady rig must not repeatedly invalidate SVG geometry');
setSvgAttribute(el,'transform','translate(10.1 20)');
assert.equal(writes.length,2,'a visible fractional animation step is retained');
el.setAttribute('transform','translate(30 40)');
setSvgAttribute(el,'transform','translate(10.1 20)');
assert.equal(writes.length,4,'an external animation/customization writer must not leave a stale cached transform');
assert.equal(attrs.get('transform'),'translate(10.1 20)');
setSvgAttribute(el,'opacity','0');setSvgAttribute(el,'opacity','1');
assert.equal(attrs.get('opacity'),'1','showing a previously hidden finger/prop still updates');
console.log('PASS: unchanged SVG transforms skip invalidation; fractional geometry, external writes and visibility changes are preserved');
