import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp,readFile,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import electron from 'electron';

const folder=await mkdtemp(join(tmpdir(),'lucid-boss-monitor-'));
const evaluation=`(async()=>{
  if(window.__bossMonitorCheck)return window.__bossMonitorCheck;
  window.__bossMonitorCheck={running:true};
  const checks=[],assert=(ok,message)=>{if(!ok)throw Error(message);checks.push(message);};
  const wait=ms=>new Promise(r=>setTimeout(r,ms));
  try{
    const world=window.__world,queue=world.ext.queue,monitor=queue.monitor;
    world.update=()=>{};
    const boss={id:'__monitor-test',provider:'codex',running:false};
    queue.setBoss(boss);
    const info={id:boss.id,title:'Check the office',provider:'codex',run:null};
    const item={id:'one',runId:null,ordinal:1,type:'assistant_message',status:'completed',updatedAt:'2026-10-31T12:00:00Z',data:{text:'Reviewed the robot assignments.'}};
    monitor.api={itemsSince:async()=>[item],threadInfo:async()=>info,peek:async()=>null,image:async()=>null,readText:async()=>null};
    world.showRoom('queue');await wait(500);
    const el=monitor.el,screen=el.querySelector('.screen');
    const localBounds=()=>({width:el.offsetWidth,height:el.offsetHeight,x:el.offsetLeft,y:el.offsetTop});
    const before=localBounds();
    el.focus();el.click();await wait(1500);
    const after=localBounds();
    assert(el.classList.contains('is-open')&&el.getAttribute('aria-pressed')==='true','click toggles the monitor toward the viewer');
    assert(before.width===110&&before.height===72&&JSON.stringify(before)===JSON.stringify(after),'turning preserves fixed110x72 size and position in room coordinates');
    assert(screen.querySelector('.os .dock')&&screen.querySelector('.win-layer'),'revealed face uses the ordinary robot desktop');
    assert(monitor.director.info.id===boss.id&&monitor.director.items.has('one'),'ordinary director receives the actual thread and its activity');
    assert(screen.inert&&getComputedStyle(screen).pointerEvents==='none','desktop contents remain noninteractive');
    assert(!el.querySelector('.bm-chat,.bm-close,.bm-front > header,.bm-activity'),'no special panel or extra controls outside the ordinary desktop');
    queue.setBoss({...boss,running:true});await wait(100);
    assert(el.classList.contains('is-open'),'routine state refresh leaves monitor turned');
    el.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
    assert(el.classList.contains('is-open'),'monitor stays turned without an automatic close action');
    el.click();assert(!el.classList.contains('is-open'),'same monitor toggles back');
    el.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
    assert(el.classList.contains('is-open')&&document.activeElement===el,'keyboard toggle retains focus on monitor');
    const host=document.createElement('div');queue.el.append(host);
    const restored=new monitor.constructor(host,0,0);restored.api=monitor.api;restored.set(boss);
    assert(restored.el.classList.contains('is-open'),'orientation survives a room rebuild');
    restored.destroy();host.remove();
    let resolve;monitor.turn(false);monitor.api.itemsSince=()=>new Promise(r=>resolve=r);
    el.click();await wait(0);monitor.set(null);resolve([{...item,id:'late'}]);await wait(0);
    assert(el.getAttribute('aria-disabled')==='true'&&!monitor.director.items.has('late'),'removing orchestrator rejects a stale fetch');
    monitor.api.itemsSince=async()=>[item];monitor.set(boss);el.click();await wait(1000);
    if(!el.classList.contains('is-open'))el.click();
    window.__bossMonitorCheck={ok:true,checks};
  }catch(error){window.__bossMonitorCheck={ok:false,error:String(error),stack:error.stack,checks};}
  return window.__bossMonitorCheck;
})()`;
const file=join(folder,'evaluation.js');await writeFile(file,evaluation);
const env={...process.env,LUCID_SHOT:folder,LUCID_SHOT_PROFILE:join(folder,'profile'),LUCID_SHOT_COUNT:'3',LUCID_SHOT_EVERY:'4000',LUCID_SHOT_QUIT:'1',LUCID_EVAL_FILE:file};
delete env.ELECTRON_RUN_AS_NODE;delete env.LUCID_EVAL;
await new Promise((resolve,reject)=>{const child=spawn(electron,['.'],{env,stdio:'inherit'});child.on('error',reject);child.on('exit',code=>code===0?resolve():reject(Error('Electron exited '+code)));});
const log=await readFile(join(folder,'eval.log'),'utf8');
console.log('Artifacts: '+folder);console.log(log);
assert(log.includes('"ok": true')&&!log.includes('"ok": false'),'native monitor interactions pass');
