// Real Electron interactions against an isolated renderer build and fixture IPC.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
if (!process.versions.electron) {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
  require('node:child_process').spawn(require('electron'), [__filename, ...process.argv.slice(2)], { env, windowsHide: true, stdio: 'inherit' }).on('exit', code => process.exit(code ?? 1));
} else {
  const { app, BrowserWindow } = require('electron');
  const out = path.resolve(process.argv[2] || fs.mkdtempSync(path.join(os.tmpdir(), 'lucid-coin-ui-')));
  const build = path.resolve(process.argv[3] || 'dist');
  fs.mkdirSync(path.join(out, 'profile'), { recursive: true });
  app.setPath('userData', path.join(out, 'profile'));
  Object.assign(process.env, { LUCID_SHOT: out, LUCID_SHOT_PROFILE: app.getPath('userData'), LUCID_SHOT_EVERY: '600000', LUCID_AUTO_SCOPE: '(none: coin fixture)', LUCID_DEV_URL: require('node:url').pathToFileURL(path.join(build, 'index.html')).href });
  const now = new Date(), day = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  fs.writeFileSync(path.join(out, 'profile', 'settings.json'), JSON.stringify({ wallet: { v: 2, ledger: { welcome: 20 }, spent: 8, owned: ['floor:oak'], daily: { last: day, streak: 1 } } }));
  const thread = { id: 'coin-worker', projectId: 'coin-project', title: 'Verify a finished robot with a long task title and actual recorded API spend', provider: 'codex', model: 'Fixture model', updatedAt: now.toISOString(), runStatus: 'running', pinned: true, manager: { projectId: 'coin-project', role: 'Engineer' }, settled: false, question: null };
  const data = { projects: [{ id: 'coin-project', title: 'Coin fixture office', root: out, icon: null, scratch: false }], threads: [thread], shipped: { total: 0, today: 0 } };
  const totals = { tokens: 0, costUsd: 0, byHarness: {}, byModel: {}, byProject: {} };
  const usage = { updatedAt: now.toISOString(), windows: { today: totals, week: totals, last5h: totals }, limits: {}, errors: [] };
  let cost = 4.25;
  Object.assign(require('../electron/t3.cjs'), { world: () => data, officeTasks: () => [], watchThread: () => () => {}, pendingRequests: () => [], resolvedRequestsSince: () => [], userMessagesSince: () => [], itemsSince: () => [], listProjects: () => data.projects, coinBindings: () => [] });
  Object.assign(require('../electron/usage.cjs'), { getUsage: async () => usage, getCoinSources: async () => ({ usage, sources: [{ key: 'codex:coin-fixture', threadId: thread.id, title: thread.title, status: thread.runStatus, costUsd: cost }] }) });
  Object.assign(require('../electron/environments.cjs'), { getEnvironments: async () => ({ localId: 'fixture', buildings: [{ id: 'fixture', label: 'Coin fixture office', local: true }] }) });
  Object.assign(require('../electron/weather.cjs'), { getWeather: async () => null, lastError: () => null });
  require('../electron/main.cjs');
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  let win;
  const ev = code => win.webContents.executeJavaScript(code);
  const checks = [], check = (ok, label) => { assert(ok, label); checks.push(label); };
  const capture = async name => { await wait(120); fs.writeFileSync(path.join(out, name + '.png'), (await win.webContents.capturePage()).toPNG()); };
  // Click a drawn park thing (there are no park buttons): its spot centre, projected to the screen.
  const clickPark = async kind => {
    const p = await ev(`(()=>{const w=window.__world,s=w.park.toys.spots.find(s=>s.kind===${JSON.stringify(kind)}),r=w.root.getBoundingClientRect(),z=r.width/w.root.offsetWidth;return {x:Math.round(r.left+s.x*z),y:Math.round(r.top+s.y*z)}})()`);
    win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...p });
    win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...p }); await wait(80);
  };
  const click = async selector => {
    const p = await ev(`(()=>{const e=document.querySelector(${JSON.stringify(selector)}),r=e.getBoundingClientRect();return {x:Math.round(r.left+r.width/2),y:Math.round(r.top+r.height/2)}})()`);
    win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...p });
    win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...p }); await wait(80);
  };
  app.whenReady().then(async () => {
    try {
      await wait(250); win = BrowserWindow.getAllWindows()[0];
      for (let i = 0; i < 150 && !await ev('!!window.__coinRewards && !!window.__world?.desks.get("coin-worker")'); i++) await wait(100);
      await ev('window.__coinRewards.refresh()');
      check(await ev('!window.__gameSound.context'), 'startup does not create an audio context');
      await ev('window.__world.showDesk(window.__world.desks.get("coin-worker"))'); await wait(800);
      await capture('01-working');
      const before = await ev('window.__wallet.balance');
      cost = 7.5;
      await ev('window.__coinRewards.refresh()');
      check(await ev('window.__wallet.rewards.length===0'), 'running work cannot be collected');
      thread.runStatus = 'completed'; await ev('window.__refresh();window.__coinRewards.refresh()'); await wait(500);
      check(await ev('!!document.querySelector(".desk-coins")'), 'finished robot has a monitor coin stack');
      check(await ev('document.querySelector(".desk-coins").parentElement.classList.contains("screen")'), 'reward is a scene inside the actual computer screen');
      check(await ev('(()=>{const b=document.querySelector(".desk-coins").getBoundingClientRect(),s=document.querySelector(".desk-coins").parentElement.getBoundingClientRect();return Math.abs(b.left-s.left)<1&&Math.abs(b.top-s.top)<1&&Math.abs(b.width-s.width)<1&&Math.abs(b.height-s.height)<1})()'), 'reward fills the screen without protruding over the desk');
      const amount = await ev('window.__wallet.rewards[0].amount');
      check(amount >= 3.25 && await ev('window.__wallet.balance') === before, 'real usage accrues without auto-crediting the balance');
      await capture('02-ready');
      await click('.desk-coins');
      check(await ev('window.__wallet.balance') === Math.round((before + amount) * 1e6) / 1e6, 'real pointer collects coins immediately');
      check(await ev('window.__gameSound.context?.state === "running" && window.__gameSound.voices.size > 0'), 'collection plays the real layered Web Audio chime');
      check(await ev('document.querySelectorAll(".coin-transfer").length===7'), 'collection animates a bounded stream into the wallet');
      await wait(850);
      check(await ev('document.querySelectorAll(".coin-transfer").length===0 && window.__gameSound.voices.size===0'), 'animation and audio resources finish cleanly');
      await capture('03-collected');
      await ev('window.__coinRewards.refresh()');
      check(await ev('window.__wallet.rewards.length===0'), 'refresh does not duplicate collected rewards');
      await click('#game-sound');
      check(await ev('!window.__gameSound.enabled && document.querySelector("#game-sound").getAttribute("aria-pressed")==="false"'), 'mute is visible and immediately applied');
      cost += 1.25; thread.pinned = false; thread.settled = true;
      win.webContents.debugger.attach('1.3');
      await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
      await ev('window.__world.revealThread(null);window.__world.unfocus(false)');
      await ev('window.__refresh()'); await ev('window.__coinRewards.refresh()');
      await ev('window.__coinRewards.render()');
      check(await ev('window.__world.desks.has("coin-worker") && !!document.querySelector(".desk-coins") && !document.querySelector(".coin-tray").hidden'), 'uncollected rewards keep a settled ordinary robot desk present');
      await click('.coin-tray summary');
      win.webContents.focus();
      await ev('document.querySelector(".coin-reward-row").focus()');
      check(await ev('document.activeElement.classList.contains("coin-reward-row")'), 'collection row accepts keyboard focus');
      win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Return' });
      win.webContents.sendInputEvent({ type: 'char', keyCode: '\r' });
      win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Return' }); await wait(100);
      check(await ev('window.__wallet.rewards.length===0 && document.activeElement.id==="coin-bank"'), 'keyboard collection restores focus to the wallet');
      check(await ev('window.__world.desks.has("coin-worker")'), 'collecting keeps the desk until it is removed');
      check(await ev('window.__gameSound.voices.size===0'), 'muted collection produces no voices');
      check(await ev('document.querySelectorAll(".coin-transfer").length===0'), 'reduced motion collects immediately without flying coins');
      win.setSize(980, 640); await wait(300);
      check(await ev('(()=>{const r=document.querySelector("#game-sound").getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight})()'), 'controls fit the smallest app window');
      await capture('04-compact');
      win.setSize(1480, 920); await wait(100);
      await ev(`(()=>{const w=window.__world,r=w.rooms.find(r=>r.kind==='break'),br=w.ext.break;w.stopCameraMotion();w.cam={s:1.5,x:w.scene.clientWidth/2-(r.x+br.arcade.cx)*1.5,y:w.scene.clientHeight/2-(r.y+150)*1.5};w.apply();void br.arcade.boot()})()`); await wait(450);
      await click('[data-room-control="tv-power"]');
      check(await ev('window.__world.ext.break.arcade.powered===false'), 'real TV control powers off without destroying the game');
      await click('[data-room-control="tv-power"]');
      check(await ev('window.__world.ext.break.arcade.powered===true'), 'TV control powers back on');
      await capture('05-tv');
      await ev(`(()=>{const w=window.__world,r=w.rooms.find(r=>r.kind==='break'),br=w.ext.break;void br.movie.start();void br.movie.play(()=>{});w.stopCameraMotion();w.cam={s:1.35,x:w.scene.clientWidth/2-(r.x+br.movie.cx)*1.35,y:w.scene.clientHeight/2-(r.y+180)*1.35};w.apply()})()`); await wait(450);
      await click('[data-room-control="movie-screen"]');
      check(await ev('window.__world.ext.break.movie.screenRaised===true'), 'real roller control raises the projector screen');
      await wait(1100); await capture('06-screen-raised');
      await click('[data-room-control="movie-screen"]');
      check(await ev('window.__world.ext.break.movie.screenRaised===false'), 'roller control lowers the screen and resumes the film');
      await wait(1100); await capture('07-movie');
      await ev('window.__world.showPark()'); await wait(1100);
      await clickPark('tree');
      check(await ev('document.querySelectorAll(".park-effect").length>0'), 'clicking a real park tree produces finite foliage effects');
      await capture('08-tree'); await wait(1700);
      await clickPark('pond');
      check(await ev('document.querySelectorAll(".park-ripple").length>0'), 'pond clicks produce visible ripples');
      await capture('09-pond'); await wait(1700);
      check(await ev('document.querySelectorAll(".park-effect").length===0'), 'park transients release their elements after finishing');
      await ev('window.__coinRewards.destroy();window.__soundscape?.destroy()'); await ev('window.__gameSound.destroy()');
      check(await ev('!document.querySelector(".coin-tray") && window.__gameSound.context===null'), 'feature owners release controls, timers and audio');
      check(await ev('window.__errs.length===0'), 'fixture has no renderer errors');
      const result = { ok: true, checks, out }; fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2)); app.exit(0);
    } catch (error) { console.error(error); fs.writeFileSync(path.join(out, 'failure.json'), JSON.stringify({ error: String(error), checks, errors: await ev('window.__errs').catch(() => []) }, null, 2)); await capture('failure'); app.exit(1); }
  });
}
