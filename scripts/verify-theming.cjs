const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { stripTypeScriptTypes } = require('node:module');
function moduleSource(file) {
  return stripTypeScriptTypes(fs.readFileSync(file, 'utf8').replace(/^import .*?;\n/gm, '').replace(/export /g, ''), { mode: 'transform' });
}
const context = { structuredClone, console };
vm.runInNewContext(moduleSource('src/decor/decor.ts') + '\n' + moduleSource('src/office/appearances.ts') + '\n' + moduleSource('src/office/coin-ledger.ts') + '\n' + moduleSource('src/office/shop.ts') + '\nglobalThis.test={Wallet,CATALOG,currentSeason,ROOM_STYLES};', context);
const { Wallet, CATALOG, currentSeason, ROOM_STYLES } = context.test;
let saved = { ledger: { welcome: 400 }, spent: 0, owned: [], v: 2 }, writes = 0;
const wallet = new Wallet(() => saved, state => { saved = state; writes++; });
let changes = 0; wallet.onChange = () => changes++;
assert(wallet.owns('computer:classic'));
assert(wallet.buy('computer:mint'));
assert.equal(wallet.balance, 335);
assert(!wallet.buy('computer:mint'), 'duplicate purchases do not spend coins');
assert.equal(writes, 1);
const garden = ROOM_STYLES.find(s => s.id === 'garden');
const keys = [`floor:${garden.floor}`, `wall:${garden.wall}`, `computer:${garden.computer}`];
assert(wallet.buyMany(keys));
assert.equal(wallet.balance, 235, 'collections charge only missing parts');
assert.equal(changes, 2, 'collection emits one change');
assert(wallet.buyMany(keys)); assert.equal(writes, 2, 'equipping owned collection does not write wallet');
assert(!wallet.buyMany(['computer:graphite', 'floor:terrazzo']));
assert.equal(wallet.balance, 235, 'unaffordable collection spends nothing');
assert(!wallet.owns('computer:graphite'), 'unaffordable collection grants nothing');
assert(!wallet.buy('decor:arcade'), 'purchase API enforces level lock');
const off = CATALOG.find(it => it.season && it.season !== currentSeason());
assert(!wallet.buy(off.key), 'off-season purchases rejected');
const old = JSON.stringify(saved);
assert(!wallet.buyMany(['computer:cream', 'invalid:item']));
assert.equal(JSON.stringify(saved), old, 'invalid mixed collection is atomic');
assert(wallet.buyMany(['computer:cream', 'computer:cream']));
assert.equal(wallet.balance, 190, 'duplicate keys charged once');
const reload = new Wallet(() => JSON.parse(JSON.stringify(saved)), () => {});
assert(reload.owns('computer:mint')); assert(reload.owns('floor:oak')); assert.equal(reload.balance, 190);
assert.equal(new Set(CATALOG.map(it => it.key)).size, CATALOG.length);
for (const style of ROOM_STYLES) for (const key of [`floor:${style.floor}`, `wall:${style.wall}`, `computer:${style.computer}`]) assert(CATALOG.some(it => it.key === key));
console.log('PASS: theme collections, missing-piece pricing, atomic balance checks, duplicate protection, level and season rules, catalog consistency and reload ownership.');
